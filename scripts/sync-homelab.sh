#!/bin/bash
# Snapshot this server's config into ~/homelab (sanitized). Idempotent.
set -euo pipefail
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_DIR"

# Rootless Podman needs a runtime dir; cron runs with a bare environment.
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
USER_NAME=${SUDO_USER:-$(id -un)}
HOME_DIR=$(getent passwd "$USER_NAME" 2>/dev/null | cut -d: -f6)
[ -n "$HOME_DIR" ] || HOME_DIR="/home/$USER_NAME"


copy_file() { # src dst [mode]
  local src=$1 dst=$2 mode=${3:-}
  [ -r "$src" ] || return 0
  mkdir -p "$(dirname "$dst")"
  cp "$src" "$dst"
  [ -n "$mode" ] && chmod "$mode" "$dst" || true
}

# --- system (readable /etc subset) ---
copy_file /etc/hostname system/etc/hostname
copy_file /etc/hosts system/etc/hosts
copy_file /etc/fstab system/etc/fstab
copy_file /etc/network/interfaces system/etc/network/interfaces
copy_file /etc/apk/repositories system/etc/apk/repositories
copy_file /etc/apk/world system/etc/apk/world
# Nix is a declared dependency of the pinned flake. The live host gets it on
# the next --packages bootstrap, so keep it in the snapshot until then.
if ! grep -qx 'nix' system/etc/apk/world; then
  printf 'nix\n' >> system/etc/apk/world
  LC_ALL=C sort -o system/etc/apk/world system/etc/apk/world
fi
# These tools come from the Nix profile. Keep them out of the apk snapshot so
# a later sync cannot reintroduce duplicates.
for pkg in btop chafa eza fastfetch fd fzf github-cli jq lazygit rclone ripgrep yazi yazi-cli zoxide; do
  sed -i "/^${pkg}$/d" system/etc/apk/world
done
copy_file /etc/modules system/etc/modules
copy_file /etc/ssh/sshd_config system/etc/ssh/sshd_config
copy_file /etc/rc.conf system/etc/rc.conf
copy_file /etc/local.d/wifi-powersave.start system/etc/local.d/wifi-powersave.start
copy_file /etc/dnsmasq.conf system/etc/dnsmasq.conf
copy_file /etc/os-release system/etc/os-release

# User shell and editor config (text only, no history or secrets)
copy_file "$HOME_DIR/.zshrc" configs/zsh/.zshrc
for f in "$HOME_DIR"/.config/zsh/* "$HOME_DIR"/.config/zsh/.[!.]*; do
  [ -f "$f" ] || continue
  copy_file "$f" "configs/zsh/$(basename "$f")"
done
for f in "$HOME_DIR"/.config/nvim/* "$HOME_DIR"/.config/nvim/.[!.]*; do
  [ -f "$f" ] || continue
  case "$(basename "$f")" in .git|data|lazy-lock.json) continue ;; esac
  copy_file "$f" "configs/nvim/$(basename "$f")"
done

# OpenRC service scripts we maintain
for svc in 9router hermes-gateway paseo portfolio-api; do
  copy_file "/etc/init.d/$svc" "system/etc/init.d/$svc"
  copy_file "/etc/init.d/$svc" "init/$svc.openrc"
  for dst in "system/etc/init.d/$svc" "init/$svc.openrc"; do
    sed -i -e "s|$HOME_DIR|{{HOMELAB_HOME}}|g" -e "s|$USER_NAME|{{HOMELAB_USER}}|g" "$dst" 2>/dev/null || true
  done
done
sed -i -e "s|$HOME_DIR|\$HOME|g" -e "s|$USER_NAME@|\$(id -un)@|g" configs/zsh/* 2>/dev/null || true
# Keep the Nix profile ahead of apk tools. The live shell picks this up later.
if [ -f configs/zsh/environment ] && ! grep -q '\.nix-profile/bin' configs/zsh/environment; then
  printf '\n# Nix user profile, pinned tools from flake.nix\nexport PATH="$HOME/.nix-profile/bin:$PATH"\n' >> configs/zsh/environment
fi

# runlevels (default)
if [ -d /etc/runlevels/default ]; then
  mkdir -p system/etc/runlevels
  ls /etc/runlevels/default 2>/dev/null | sort > system/etc/runlevels/default.list || true
fi

# Stable live inventory. No timestamps here, so unchanged machines produce no
# diff. Unmanaged containers are reported as a count plus a fingerprint, not by
# name: their names may belong to a private checkout and must never enter a
# tracked file.
{
  echo "# Live snapshot of takamatsu. Generated by scripts/sync-homelab.sh."
  echo "host_model=$(cat /sys/class/dmi/id/product_name 2>/dev/null || echo unknown)"
  echo "arch=$(uname -m)"
  . /etc/os-release 2>/dev/null || true
  echo "os=${ID:-unknown} ${VERSION_ID:-unknown}"

  # Approved homelab services are hardcoded here so a restart of the dashboard
  # does not look like an unknown container. Anything else running from outside
  # the repo is reported by count and fingerprint only.
  managed_list=$( {
    printf '%s\n' homelab-fetch homelab-shell kanaos wordcraft-files wordcraft-web
    find "$REPO_DIR/podman" -maxdepth 1 -name '*.yml' -exec awk '/^[[:space:]]*container_name:/{print $2}' {} + 2>/dev/null
  } | sort -u )
  running_list=$(podman ps --format '{{.Names}}' 2>/dev/null | sort || true)

  echo "podman_containers:"
  printf '%s\n' "$running_list" | awk -v m="$managed_list" '
    BEGIN { n = split(m, a, "\n"); for (i = 1; i <= n; i++) if (a[i] != "") mg[a[i]] = 1 }
    NF {
      for (k in mg) if ($0 == k || index($0, k "-") == 1) { print; next }
    }
  ' | sort || true

  unmanaged_list=$(printf '%s\n' "$running_list" | awk -v m="$managed_list" '
    BEGIN { n = split(m, a, "\n"); for (i = 1; i <= n; i++) if (a[i] != "") mg[a[i]] = 1 }
    NF {
      for (k in mg) if ($0 == k || index($0, k "-") == 1) next
      print
    }
  ' | sort || true)
  echo "unmanaged_container_count: $(printf '%s\n' "$unmanaged_list" | awk 'NF' | wc -l | tr -d ' ')"
  echo "unmanaged_container_fingerprint: $(printf '%s\n' "$unmanaged_list" | sha256sum | cut -c1-16)"

  echo "podman_compose_dirs:"
  find "$REPO_DIR/podman" -maxdepth 1 -name '*.yml' -printf '%f\n' 2>/dev/null | sort || true
  echo "openrc_default:"
  ls /etc/runlevels/default 2>/dev/null | sort || true
  echo "custom_init:"
  ls /etc/init.d 2>/dev/null | grep -E '^(9router|hermes-gateway|paseo|portfolio-api)$' | sort || true
} > system/inventory.txt

# user crontab (fallback to crontab -l)
if [ -r "/etc/crontabs/$USER_NAME" ]; then
  copy_file "/etc/crontabs/$USER_NAME" system/crontab
else
  crontab -l > system/crontab 2>/dev/null || true
fi

# Sanitize: remove entries pointing at non-managed checkouts and raw home paths.
awk '/^[[:space:]]*(#|$)/ || /(\$HOME|\/home\/[^ ]+)\/(homelab|containers|\.hermes|\.local|storage|\.npm-global)([ \/]|$)/' system/crontab > system/crontab.tmp && mv system/crontab.tmp system/crontab
sed -i -e "s|$HOME_DIR|\$HOME|g" -e "s|$USER_NAME@|\$(id -un)@|g" system/crontab

# adguard runtime config (sanitized) if readable (repo copy kept otherwise)
for agh in "$HOME_DIR"/containers/adguardhome/conf/AdGuardHome.yaml "$HOME_DIR"/containers/adguardhome/AdGuardHome.yaml; do
  if [ -r "$agh" ]; then
    cp "$agh" services/adguardhome/AdGuardHome.yaml
    break
  fi
done
# Sanitize the repo copy even when the live file is not readable by this user.
# Retired services must not reappear through a later sync.
if [ -f services/adguardhome/AdGuardHome.yaml ]; then
  awk '
    /^[[:space:]]*- domain: (dockge|cockpit|uptime-kuma)\.lab/ { skip=3 }
    skip > 0 { skip--; next }
    { print }
  ' services/adguardhome/AdGuardHome.yaml > services/adguardhome/AdGuardHome.yaml.tmp
  mv services/adguardhome/AdGuardHome.yaml.tmp services/adguardhome/AdGuardHome.yaml
  sed -i 's/^\(  password:\).*/\1 ""/' services/adguardhome/AdGuardHome.yaml 2>/dev/null || true
fi


# keep the one-file bootstrap in sync with this snapshot
./scripts/generate-bootstrap.sh >/dev/null 2>&1 || true
